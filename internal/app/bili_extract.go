package app

import (
	"regexp"
	"strconv"
	"strings"

	"netease-music-mygo/internal/bilibili"
	"netease-music-mygo/internal/netease"
)

// A biliCand is a song guessed from a video: the line the uploader wrote,
// where in the video it starts when the text says, and what it matched on
// NetEase. Which side of the line is the title and which the artist is
// left to the search to tell.
type biliCand struct {
	Raw     string
	StartMs int64
	Track   *netease.Track
}

// biliCandMost is the most songs one video is taken to hold.
const biliCandMost = 500

var (
	// A timestamp at the start of a line: 00:00, 1:02:03, [00:00].
	biliStampRe = regexp.MustCompile(`^[\[\(（【]?(\d{1,2})\s*[:：]\s*(\d{2})(?:\s*[:：]\s*(\d{2}))?[\]\)）】]?`)
	// What a numbered list, a bullet or a part's index starts with.
	biliLeadRe = regexp.MustCompile(`^(?:[-–—•·*▪]+\s*|\d{4}\s*[-./年]\s*\d{1,2}\s*[-./月]\s*\d{1,2}\s*日?\s*|\d{1,3}\s*[.、)）:：]\s+|\d{1,3}\s+|[Pp]\d{1,2}\s*[:：.、)）]?\s*|第\s*\d{1,3}\s*[首曲]\s*[.、:：]?\s*)`)
	// A year written after a song, in brackets or bare.
	biliYearRe = regexp.MustCompile(`[（(]\s*(?:19|20)\d{2}\s*[)）]|(?:^|[\s\-–—·])(?:19|20)\d{2}\s*$`)
	// A separator between a song and its artist, spaced so a name's own
	// dashes are not taken for it.
	biliSepRe = regexp.MustCompile(`\s+[-–—]\s+|\s+[/／]\s+|\s*[|｜]\s*`)
	// A part or a chapter that names a section, not a song.
	biliSectionRe = regexp.MustCompile(`(?i)歌单|年度|合集|精选|电台|曲目|整理|第\s*\d+\s*[集期]|vol\.?\s*\d|ep\.?\s*\d|part\s*\d|^p\d+$|cd\s*\d|track\s*list|set\s*list|mix\b`)
	// Lines that say nothing about a song.
	biliNoiseRe = regexp.MustCompile(`(?i)^(https?:|@|#|私信|开场|片头|片尾|本视频|视频|仅供|版权|如有侵权|关注|点赞|投币|收藏|三连|求|感谢|声明|简介|更新|订阅|收听|播放|歌曲|歌单|曲目|音乐由|曲目表|tracklist|setlist|track\s*list|如果你|请|别忘了|戴上耳机|去听|这是一个|需要|私聊)`)
	// A list marker that stands for the whole track, not a song.
	biliMarkerRe = regexp.MustCompile(`(?i)^(repeat|end|outro|ending|fin\.?|完|结束|循环)\s*[。.!！]?$`)
	// An aside in brackets, which a title often carries besides its name.
	biliAsideRe = regexp.MustCompile(`[（(【\[][^)）】\]]*[)）】\]]`)
	// A year at the very end of a line, after whatever comes before it.
	biliTailYearRe = regexp.MustCompile(`(?:19|20)\d{2}\s*$`)
	// A trailing tag, as uploaders add under a list.
	biliTagRe = regexp.MustCompile(`\s*#[^\s#]+`)
	// An uploader saying a machine made the music, which the site does not
	// hold.
	biliAIRe = regexp.MustCompile(`(?i)ai\s*(生成|创作|作曲|编曲|演唱|制作|合成)|suno|udio\s*\.?\s*ai|aigc|人工智能\s*(生成|创作|作曲)|ai[-\s]?generated|generated by ai|made with ai`)
)

// biliExtract guesses the songs a video holds, from the most reliable
// source to the least: its parts, the timestamps and lists under it, the
// chapters on its timeline, what it mentions in quotes, and the
// uploader's own comment.
func biliExtract(v bilibili.Video, comment string, chapters []bilibili.Chapter) []biliCand {
	parts := biliFromPages(v)
	text := biliFromText(v.Desc)
	pick := parts
	if len(text) > len(pick) {
		// A part's title is short where the text under the video still
		// holds the whole line, as a year's mix does.
		pick = text
	}
	if len(pick) == 0 {
		pick = biliFromChapters(chapters)
	}
	// A chapter names the song; the uploader's comment under the video
	// often names its artist too, so a comment that names more is read in
	// its place.
	pick = biliUnique(pick)
	if c := biliUnique(biliFromText(comment)); len(c) > 0 && (len(pick) == 0 || (len(c) >= len(pick) && biliNamedRows(c) > biliNamedRows(pick))) {
		pick = c
	}
	if len(pick) > 0 {
		return pick
	}
	if c := biliFromQuotes(v.Desc); len(c) > 0 {
		return biliUnique(c)
	}
	return nil
}

// biliNamedRows counts the lines that name two things, a song and beside
// it whoever plays it, which a bare chapter does not.
func biliNamedRows(cs []biliCand) int {
	n := 0
	for _, c := range cs {
		if strings.ContainsAny(c.Raw, "/／") || biliSepRe.MatchString(c.Raw) {
			n++
		}
	}
	return n
}

// biliFromPages reads a video's parts, one song each, where their titles
// are songs rather than sections of a longer mix.
func biliFromPages(v bilibili.Video) []biliCand {
	if len(v.Pages) < 2 {
		return nil
	}
	for _, p := range v.Pages {
		if biliSectionRe.MatchString(p.Title) {
			return nil
		}
	}
	var out []biliCand
	at := int64(0)
	for _, p := range v.Pages {
		c, ok := biliLine(p.Title)
		if !ok {
			continue
		}
		c.StartMs = at
		out = append(out, c)
		at += p.Duration.Milliseconds()
	}
	return out
}

// biliFromChapters reads the stretches a video's timeline names.
func biliFromChapters(chapters []bilibili.Chapter) []biliCand {
	var out []biliCand
	for _, ch := range chapters {
		if biliSectionRe.MatchString(ch.Title) || biliNoiseRe.MatchString(ch.Title) {
			continue
		}
		c, ok := biliLine(ch.Title)
		if !ok {
			continue
		}
		c.StartMs = ch.From.Milliseconds()
		out = append(out, c)
	}
	return out
}

// biliFromText reads a text's tracklist: its timestamps first, then a
// numbered list, then a plain one.
func biliFromText(text string) []biliCand {
	for _, read := range []func(string) []biliCand{biliFromStamps, biliFromNumbered, biliFromPlain} {
		if c := read(text); len(c) > 0 {
			return c
		}
	}
	return nil
}

// biliFromStamps reads the lines that start with a timestamp.
func biliFromStamps(text string) []biliCand {
	var out []biliCand
	for _, line := range strings.Split(text, "\n") {
		c, ok := biliLine(line)
		if !ok || c.StartMs < 0 {
			continue
		}
		out = append(out, c)
	}
	return out
}

// biliFromNumbered reads a list whose lines start with a number, a bullet
// or a part's index.
func biliFromNumbered(text string) []biliCand {
	var out []biliCand
	for _, line := range strings.Split(text, "\n") {
		trimmed := strings.TrimSpace(biliLeadRe.ReplaceAllString(strings.TrimSpace(line), ""))
		if trimmed == strings.TrimSpace(line) || !biliSepRe.MatchString(trimmed) {
			continue
		}
		if c, ok := biliLine(line); ok {
			out = append(out, c)
		}
	}
	return out
}

// biliFromPlain reads the lines of a plain list, told by their separator,
// and only when several of them make a list rather than a sentence.
func biliFromPlain(text string) []biliCand {
	var out []biliCand
	for _, line := range strings.Split(text, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || !biliSepRe.MatchString(line) || strings.ContainsAny(line, "，。！？；") || biliSectionRe.MatchString(line) {
			continue
		}
		a, b, ok := biliTwoParts(line)
		if !ok || len([]rune(a)) > 50 || len([]rune(b)) > 50 {
			continue
		}
		if c, ok := biliLine(line); ok {
			out = append(out, c)
		}
	}
	if len(out) < 3 {
		return nil
	}
	return out
}

// biliFromQuotes reads the names in book quotes.
func biliFromQuotes(text string) []biliCand {
	var out []biliCand
	for _, m := range biliQuoteRe.FindAllStringSubmatch(text, -1) {
		if name := biliClean(m[1]); name != "" && !biliSectionRe.MatchString(name) {
			out = append(out, biliCand{Raw: name})
		}
	}
	return out
}

// biliQuoteRe finds a song named in book quotes.
var biliQuoteRe = regexp.MustCompile(`《([^》]{1,40})》`)

// biliLine reads one line of a tracklist, with its timestamp when it
// starts with one.
func biliLine(line string) (biliCand, bool) {
	s := strings.TrimSpace(line)
	if s == "" {
		return biliCand{}, false
	}
	s = strings.TrimSpace(biliLeadRe.ReplaceAllString(s, ""))
	ms := int64(-1)
	if m := biliStampRe.FindStringSubmatch(s); m != nil {
		h, _ := strconv.Atoi(m[1])
		m2, _ := strconv.Atoi(m[2])
		s3 := 0
		if m[3] != "" {
			s3, _ = strconv.Atoi(m[3])
			ms = int64(h)*3600000 + int64(m2)*60000 + int64(s3)*1000
		} else {
			ms = int64(h)*60000 + int64(m2)*1000
		}
		s = s[len(m[0]):]
	}
	raw := biliClean(s)
	if raw == "" || biliNoiseRe.MatchString(raw) || biliMarkerRe.MatchString(raw) {
		return biliCand{}, false
	}
	if strings.Contains(raw, "http") || strings.Contains(raw, "://") {
		return biliCand{}, false
	}
	if len([]rune(raw)) < 2 || !biliHasWord(raw) {
		return biliCand{}, false
	}
	if len([]rune(raw)) > 120 {
		return biliCand{}, false
	}
	return biliCand{Raw: raw, StartMs: ms}, true
}

// biliClean drops what a line carries besides the song: the year it was
// made, the tags under it, and the marks around it.
func biliClean(s string) string {
	s = strings.TrimSpace(s)
	s = biliTagRe.ReplaceAllString(s, "")
	s = biliStripYear(s)
	s = strings.TrimSpace(s)
	s = strings.Trim(s, "|｜-–—·•、, ")
	s = strings.TrimSpace(s)
	if s == "" {
		return ""
	}
	return strings.Join(strings.Fields(s), " ")
}

// biliStripYear takes the year off the end of a line, and the bracket it
// was written in.
func biliStripYear(s string) string {
	for i := 0; i < 3; i++ {
		t := biliYearRe.ReplaceAllString(s, "")
		if t == s {
			// A year written straight after a bracket: "…（1984）1980".
			if loc := biliTailYearRe.FindStringIndex(s); loc != nil && loc[0] > 0 {
				t = s[:loc[0]]
			}
		}
		t = strings.TrimRight(strings.TrimSpace(t), "-–—·、| ")
		if t == s || t == "" {
			return strings.TrimSpace(t)
		}
		s = t
	}
	return s
}

// biliTwoParts splits a line into the two things a tracklist line names,
// when the uploader spaced its separator.
func biliTwoParts(s string) (a, b string, ok bool) {
	loc := biliSepRe.FindStringIndex(s)
	if loc == nil {
		return "", "", false
	}
	sep := s[loc[0]:loc[1]]
	if !strings.ContainsAny(sep, "|｜") && !strings.Contains(sep, " ") {
		return "", "", false
	}
	a, b = strings.TrimSpace(s[:loc[0]]), strings.TrimSpace(s[loc[1]:])
	if a == "" || b == "" || len([]rune(a)) < 2 || len([]rune(b)) < 2 {
		return "", "", false
	}
	return a, b, true
}

// biliUnique drops the repeats, keeping the order.
func biliUnique(in []biliCand) []biliCand {
	seen := map[string]bool{}
	var out []biliCand
	for _, c := range in {
		key := biliNorm(c.Raw)
		if key == "" || seen[key] {
			continue
		}
		seen[key] = true
		out = append(out, c)
		if len(out) >= biliCandMost {
			break
		}
	}
	return out
}

// biliHasWord reports whether a line holds more than its numbers, so a
// chapter that only marks where the music starts is not taken for a song.
func biliHasWord(s string) bool {
	for _, r := range s {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= 0x4e00 && r <= 0x9fff) ||
			(r >= 0x3040 && r <= 0x30ff) {
			return true
		}
	}
	return false
}

// biliAISong reports whether a text says its music was made by AI, which
// is not looked for on the site.
func biliAISong(text string) bool {
	return biliAIRe.MatchString(text)
}
